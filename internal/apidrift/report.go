package apidrift

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Text renders the report as a deterministic plain-text summary.
func (r Report) Text() string {
	var b strings.Builder
	fmt.Fprintf(&b, "go-proxmox API return-type drift\n")
	fmt.Fprintf(&b, "  schema endpoints      : %d\n", r.SchemaEndpoints)
	fmt.Fprintf(&b, "  with structured return: %d\n", r.StructuredEndpoints)
	fmt.Fprintf(&b, "  mapped in registry    : %d\n", r.MappedEndpoints)
	fmt.Fprintf(&b, "  drifted               : %d\n", len(r.Drifted))
	fmt.Fprintf(&b, "  unmapped (structured) : %d\n", len(r.Unmapped))
	fmt.Fprintf(&b, "  stale mappings        : %d\n", len(r.StaleMappings))

	if len(r.Drifted) > 0 {
		fmt.Fprintf(&b, "\nDrift in mapped endpoints:\n")
		for _, d := range r.Drifted {
			fmt.Fprintf(&b, "  %s %s  (%s)\n", d.Method, d.Path, d.GoType)
			if len(d.Missing) > 0 {
				fmt.Fprintf(&b, "    MISSING: %s\n", strings.Join(d.Missing, ", "))
			}
			if len(d.Untyped) > 0 {
				fmt.Fprintf(&b, "    UNTYPED: %s\n", strings.Join(d.Untyped, ", "))
			}
		}
	}
	if len(r.StaleMappings) > 0 {
		fmt.Fprintf(&b, "\nStale registry mappings (not in schema):\n")
		for _, s := range r.StaleMappings {
			fmt.Fprintf(&b, "  %s\n", s)
		}
	}
	if len(r.Unmapped) > 0 {
		fmt.Fprintf(&b, "\nUnmapped endpoints with a structured return (%d):\n", len(r.Unmapped))
		for _, u := range r.Unmapped {
			fmt.Fprintf(&b, "  %s\n", u)
		}
	}
	return b.String()
}

// Markdown renders the report as a GitHub-flavoured markdown document suitable
// for a PR or issue body.
func (r Report) Markdown() string {
	var b strings.Builder
	b.WriteString("# go-proxmox API return-type drift\n\n")
	b.WriteString("Generated by `go run ./cmd/apidrift` against the upstream PVE `apidoc.js` schema.\n\n")
	b.WriteString("| metric | count |\n|---|---:|\n")
	fmt.Fprintf(&b, "| schema endpoints | %d |\n", r.SchemaEndpoints)
	fmt.Fprintf(&b, "| endpoints with a structured return | %d |\n", r.StructuredEndpoints)
	fmt.Fprintf(&b, "| mapped in registry | %d |\n", r.MappedEndpoints)
	fmt.Fprintf(&b, "| drifted | %d |\n", len(r.Drifted))
	fmt.Fprintf(&b, "| unmapped (structured return) | %d |\n", len(r.Unmapped))
	fmt.Fprintf(&b, "| stale mappings | %d |\n", len(r.StaleMappings))

	if len(r.Drifted) > 0 {
		b.WriteString("\n## Drift in mapped endpoints\n\n")
		b.WriteString("Fields the schema declares that the mapped Go type does not fully capture.\n\n")
		for _, d := range r.Drifted {
			fmt.Fprintf(&b, "### `%s %s` → `%s`\n\n", d.Method, d.Path, d.GoType)
			if len(d.Missing) > 0 {
				fmt.Fprintf(&b, "- **Missing fields** (schema property with no Go json tag): `%s`\n", strings.Join(d.Missing, "`, `"))
			}
			if len(d.Untyped) > 0 {
				fmt.Fprintf(&b, "- **Untyped sub-objects** (schema declares a nested object, Go uses map/interface): `%s`\n", strings.Join(d.Untyped, "`, `"))
			}
			b.WriteString("\n")
		}
	}
	if len(r.StaleMappings) > 0 {
		b.WriteString("\n## Stale registry mappings\n\n")
		b.WriteString("These registry entries no longer exist in the upstream schema (renamed/removed). Update `internal/apidrift/registry.go`.\n\n")
		for _, s := range r.StaleMappings {
			fmt.Fprintf(&b, "- `%s`\n", s)
		}
	}
	if len(r.Unmapped) > 0 {
		b.WriteString("\n## Unmapped endpoints with a structured return\n\n")
		b.WriteString("Endpoints whose PVE return declares named fields but which are absent from the curated registry. Each is a candidate to wire a Go type to (or is genuinely unimplemented). This is the long tail the weekly workflow tracks.\n\n")
		b.WriteString("<details><summary>")
		fmt.Fprintf(&b, "%d unmapped endpoints", len(r.Unmapped))
		b.WriteString("</summary>\n\n")
		for _, u := range r.Unmapped {
			fmt.Fprintf(&b, "- `%s`\n", u)
		}
		b.WriteString("\n</details>\n")
	}
	return b.String()
}

// JSON renders the report as indented, stable JSON for machine consumers.
func (r Report) JSON() ([]byte, error) {
	type jsonDrift struct {
		Method  string   `json:"method"`
		Path    string   `json:"path"`
		GoType  string   `json:"go_type"`
		Missing []string `json:"missing,omitempty"`
		Untyped []string `json:"untyped,omitempty"`
	}
	payload := struct {
		SchemaEndpoints     int         `json:"schema_endpoints"`
		StructuredEndpoints int         `json:"structured_endpoints"`
		MappedEndpoints     int         `json:"mapped_endpoints"`
		Drifted             []jsonDrift `json:"drifted"`
		Unmapped            []string    `json:"unmapped"`
		StaleMappings       []string    `json:"stale_mappings"`
	}{
		SchemaEndpoints:     r.SchemaEndpoints,
		StructuredEndpoints: r.StructuredEndpoints,
		MappedEndpoints:     r.MappedEndpoints,
		Drifted:             []jsonDrift{},
		Unmapped:            r.Unmapped,
		StaleMappings:       r.StaleMappings,
	}
	for _, d := range r.Drifted {
		payload.Drifted = append(payload.Drifted, jsonDrift(d))
	}
	if payload.Unmapped == nil {
		payload.Unmapped = []string{}
	}
	if payload.StaleMappings == nil {
		payload.StaleMappings = []string{}
	}
	return json.MarshalIndent(payload, "", "  ")
}
